export const supportedHomepageLocales = Object.freeze(["tr", "en"]);

export function validateHomepageLocales() {
  const locales = Object.keys(homepageLocales).sort();
  if (locales.join(",") !== [...supportedHomepageLocales].sort().join(",")) {
    throw new Error("Homepage locales must expose only the supported locale routes.");
  }

  Object.entries(homepageCopy).forEach(([key, value]) => {
    if (!value.en || !value.tr) throw new Error(`Missing homepage translation for ${key}.`);
  });

  const storyKeys = ["name", "profession", "initials", "quote", "before", "focus", "change"];
  if (homepageLocales.en.stories.length !== homepageLocales.tr.stories.length) {
    throw new Error("Homepage story collections must contain the same number of stories.");
  }
  homepageLocales.tr.stories.forEach((_, index) => {
    storyKeys.forEach((key) => {
      if (!homepageLocales.tr.stories[index][key] || !homepageLocales.en.stories[index][key]) {
        throw new Error(`Missing ${key} for homepage story ${index + 1}.`);
      }
    });
  });

  const faqKeys = ["question", "answer"];
  if (homepageLocales.en.faqItems.length !== 8 || homepageLocales.tr.faqItems.length !== 8) {
    throw new Error("Each homepage locale must contain exactly eight FAQ entries.");
  }
  homepageLocales.tr.faqItems.forEach((_, index) => {
    faqKeys.forEach((key) => {
      if (!homepageLocales.tr.faqItems[index][key] || !homepageLocales.en.faqItems[index][key]) {
        throw new Error(`Missing ${key} for homepage FAQ ${index + 1}.`);
      }
    });
  });
}
